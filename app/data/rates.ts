/** グラフ1点分のデータ（app/data/rates.ts） */
export type RatePoint = {
  /** 'YYYY-MM' 形式。X軸の dataKey に使う */
  month: string;
  /** ツールチップ用の表示ラベル（例: 2024年3月） */
  label: string;
  /** 米国の政策金利(%) */
  usRate: number;
  /** 日本の政策金利(%) */
  jpRate: number;
  /** 日米金利差(%)＝米国 − 日本 */
  spread: number;
  /** 米ドル/円の月末値 */
  usdJpy: number;
};

/** 'YYYY-MM' を「開始月から数えた通し番号」に変換する（app/data/rates.ts） */
function monthIndex(month: string): number {
  const [year, mon] = month.split('-').map(Number);
  const [startYear, startMon] = DATA_START_MONTH.split('-').map(Number);
  return (year - startYear) * 12 + (mon - startMon);
}

/** 通し番号を 'YYYY-MM' に戻す（app/data/rates.ts） */
function indexToMonth(index: number): string {
  const [startYear, startMon] = DATA_START_MONTH.split('-').map(Number);
  const total = (startYear * 12 + (startMon - 1)) + index;
  const year = Math.floor(total / 12);
  const mon = (total % 12) + 1;
  return `${year}-${String(mon).padStart(2, '0')}`;
}

/**
 * 変更イベントの配列を月次の系列に展開する（app/data/rates.ts）
 * 変更がない月は直前の値をそのまま引き継ぐ（前方補完）。
 */
function expandRateChanges(
  changes: readonly (readonly [string, number])[],
  length: number,
): number[] {
  const series: number[] = new Array(length);
  let current = changes[0][1];
  let next = 0;
  for (let i = 0; i < length; i++) {
    while (next < changes.length && monthIndex(changes[next][0]) <= i) {
      current = changes[next][1];
      next++;
    }
    series[i] = current;
  }
  return series;
}

/**
 * 政策金利・為替を結合した月次データ（app/data/rates.ts）
 * モジュール読み込み時に一度だけ組み立てる（入力が静的なため再計算の必要がない）。
 */
export const RATE_SERIES: RatePoint[] = (() => {
  // 為替データの長さを正とする。金利は前方補完するため長さの制約を受けない
  const length = Math.min(
    USD_JPY_MONTH_END.length,
    monthIndex(DATA_END_MONTH) + 1,
  );
  const usSeries = expandRateChanges(US_POLICY_RATE_CHANGES, length);
  const jpSeries = expandRateChanges(JP_POLICY_RATE_CHANGES, length);

  return Array.from({ length }, (_, i) => {
    const month = indexToMonth(i);
    const [year, mon] = month.split('-').map(Number);
    const usRate = usSeries[i];
    const jpRate = jpSeries[i];
    return {
      month,
      label: `${year}年${mon}月`,
      usRate,
      jpRate,
      // 小数計算の誤差（0.1 - (-0.1) = 0.2000000000000000x）を丸めておく
      spread: Math.round((usRate - jpRate) * 100) / 100,
      usdJpy: USD_JPY_MONTH_END[i],
    };
  });
})();

/** 最新月のデータ（app/data/rates.ts）。統計カードの「現在値」に使う */
export const LATEST_POINT: RatePoint = RATE_SERIES[RATE_SERIES.length - 1];
